def format_date(d, lang):
    m = MONTHS[lang][d.month - 1]
    if lang == "de":
        return f"{d.day}. {m} {d.year}"
    if lang == "en":
        return f"{d.day} {m} {d.year}"
    return f"{d.day} de {m} de {d.year}"
